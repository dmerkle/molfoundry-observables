"""Replay structural counts and check the generator on grammar-generated hosts.

Reference equations are never used; direct MolFoundry applications supply the
concrete successor graphs for comparison with the synthesized equations.
"""
from mfobs.core.rules import rule_graph
from mfobs.core.conditions import engine_conditions, engine_no_edges
from fractions import Fraction
from time import perf_counter
import json
from mfobs.core.engine import mf
from mfobs.core.gml import disjoint_union
from mfobs.core.conditions import transitions
from mfobs.invariants.counting import Reducer,json_reduction,evaluate
from mfobs.checks.observable_expressions import parse_expressions, count
from mfobs.core.exact_coefficients import add_vectors as add


def decode_poly(p):
    result={}
    for k,v in p.items():
        kind,i,q,e=k.split('|');result[kind,int(i),int(q),int(e)]=Fraction(v)
    return result

def verify(inputs,result,full=False):
    start=perf_counter()
    if not result['closed']:raise AssertionError('Cannot verify an incomplete run as closed')
    if inputs.definition_digest()!=result['input_definition_sha256']:raise AssertionError('Different model inputs')
    config=inputs.read('reduction');language=inputs.read('state_language')
    red=Reducer(language,max_components=config.get('max_components',10),
                joint_budget=config.get('joint_budget',20000))
    # Replay every internal count with the declared grammar. This is an exact
    # algorithm replay, not a separate trusted theorem prover.
    replayed=0
    for key,t in result['jump_terms'].items():
        rr=red.reduce(key,mf.Rule.fromGMLString(t['gml'],add=False))
        if json.loads(json.dumps(json_reduction(rr)))!=json.loads(json.dumps(t['reduction'])):raise AssertionError('Count-witness replay failed')
        replayed+=1
    obs = parse_expressions(result)
    forms = {}
    for name, terms in obs.items():
        form = decode_poly(result['basis_counting_functions'][name])
        actual = {}
        for coefficient, pattern in terms:
            reduced = red.count(rule_graph(pattern, "left"), engine_no_edges(pattern), engine_conditions(pattern))
            actual = add(actual, reduced['polynomial'], coefficient)
        if actual != form:
            raise AssertionError('Discovered expression/function mismatch')
        forms[name] = form
    ors={};engine_rules=inputs.engine_rules()
    for r in inputs.data['rules']:
        ors[r['id']]=engine_rules[r['id']]
    def make_host(n,m,closed):
        return disjoint_union([red.chain.language.instantiate(n)[0],
            red.counter.switch_states['closed' if closed else 'open'],*[red.counter.repeated]*m])
    side=range(6) if full else range(3)
    coords=[(n,m,c) for n in side for m in side for c in [False,True]]
    if full:coords += [(n,m,c) for n,m in [(10,0),(10,3),(25,2),(2,15),(40,1)] for c in [False,True]]
    counts=identities=products=0
    for n,m,closed in coords:
        host=make_host(n,m,closed)
        before={name:count(r,host) for name,r in obs.items()}
        for name,value in before.items():
            assert value==evaluate(forms[name],n,m,1-int(closed)),('count',name,n,m,closed)
            counts+=1
        for r in inputs.data['rules']:
            targets=transitions(ors[r['id']],host);changes={k:Fraction() for k in obs}
            for product,mult in targets.items():
                products+=1
                for name,o in obs.items():changes[name]+=mult*(count(o,product)-before[name])*Fraction(r['per_match'])
            for name,lhs in changes.items():
                rhs=sum(Fraction(co)*before[tgt] for tgt,co in result['equations_by_reaction'][name][r['id']].items())
                assert lhs==rhs,('generator',name,r['id'],n,m,closed,lhs,rhs)
                identities+=1
    return {'passed':True,'exact_internal_count_replays':replayed,'states':len(coords),
            'discovered_pattern_count_checks':counts,'rate_separated_generator_identities':identities,
            'actual_successor_graphs_counted':products,'seconds':perf_counter()-start,
            'host_constructor':'declared-grammar',
            'independent_host_constructor':False,
            'scope':'Witness replay uses the exact counting algorithm. Direct host matching and rewriting use independent finite semantics; '+
                    'Hosts are generated by the supplied grammar, not an independent model constructor. '+
                    'The all-size count justification is the footprint/partition theorem, conditional on rule preservation of the declared language.'}
